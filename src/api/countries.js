/**
 * Helper to pick the appropriate localized string from a bilingual {fa, en} field.
 *
 * @param {string|{fa: string, en: string}} field
 * @param {string} [lang='fa']
 * @returns {string}
 */
export function pick(field, lang = 'fa') {
  if (!field) return '';
  if (typeof field === 'string') return field;
  if (typeof field === 'object') {
    return field[lang] || field.fa || field.en || '';
  }
  return String(field);
}

