/**
 * Retrieves country details by ISO Alpha-2 code.
 * Always returns a bilingual structure.
 *
 * @param {string} countryCode
 * @returns {Promise<object|null>}
 */
export async function fetchCountryDetails(countryCode) {
  if (!countryCode) return null;
  const code = String(countryCode).trim().toUpperCase();

  if (COUNTRY_REGISTRY[code]) {
    return COUNTRY_REGISTRY[code];
  }

  // Graceful bilingual fallback for any unlisted country code
  return {
    commonName: { fa: code, en: code },
    officialName: { fa: code, en: code },
    capital: { fa: '—', en: '—' },
    currency: { fa: 'ارز بین‌المللی', en: 'International Currency' },
    languages: { fa: 'زبان رسمی کشور', en: 'Official Language' },
    region: { fa: 'بین‌المللی', en: 'International' },
    subregion: { fa: 'جهانی', en: 'Global' },
  };
}
