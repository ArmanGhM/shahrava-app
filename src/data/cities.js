/**
 * Searches curated cities by query string (matching Persian name, English name, country, etc.)
 *
 * @param {string} [query='']
 * @param {string} [continent='all']
 * @returns {Array<object>}
 */
export function searchCities(query = '', continent = 'all') {
  const q = String(query).toLowerCase().trim();

  return CITIES.filter((city) => {
    if (continent !== 'all' && city.continent !== continent) {
      return false;
    }

    if (!q) return true;

    return (
      city.nameFa.toLowerCase().includes(q) ||
      city.nameEn.toLowerCase().includes(q) ||
      city.countryFa.toLowerCase().includes(q) ||
      city.countryEn.toLowerCase().includes(q) ||
      city.taglineFa.toLowerCase().includes(q) ||
      city.taglineEn.toLowerCase().includes(q)
    );
  });
}

/**
 * Finds a curated city by ID or returns Tehran by default.
 *
 * @param {string} [cityId='tehran']
 * @returns {object}
 */
export function getCityById(cityId = 'tehran') {
  const target = String(cityId || '').toLowerCase().trim();
  const found = CITIES.find((c) => c.id.toLowerCase() === target);
  return found || CITIES[0];
}

/**
 * Safely resolves a city by ID: first checks sessionStorage for dynamically cached
 * OpenStreetMap (OSM) cities (`shahrava_osm_<id>`), then falls back to `getCityById(id)`.
 * Solves Bug 2 where OSM cities fallback unexpectedly to Tehran.
 *
 * @param {string} cityId
 * @returns {object}
 */
export function resolveCitySafe(cityId) {
  if (!cityId) return CITIES[0];
  const id = String(cityId).trim();

  if (typeof window !== 'undefined' && window.sessionStorage) {
    try {
      const stored = window.sessionStorage.getItem(`shahrava_osm_${id}`);
      if (stored) {
        const parsed = JSON.parse(stored);
        if (parsed && (parsed.id || parsed.nameFa || parsed.nameEn)) {
          return parsed;
        }
      }
    } catch (e) {
      console.warn('resolveCitySafe sessionStorage check failed:', e);
    }
  }

  return getCityById(id);
}
